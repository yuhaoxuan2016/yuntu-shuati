// 进库提示判据（2026-10-07）
//
// 起因：练习页那条「云同步还没完成，现在可能读不到上次进度」横幅，判据写的是
//   `state === 'syncing'`。但**进练习页时同步压根不启动**（唯一自动入口是 App.vue 的启动钩子，
//   且受 4 秒延迟 + 10 分钟节流）⇒ 进页面那一刻状态只会是 idle / 上次的 ok / 上次的 fail，
//   「正在同步」这个值基本凑不出来 ⇒ **横幅一次都没出现过**（rabbit 2026-10-07 实测）。
//
// 正确口径（rabbit 2026-10-07 纠正）：「横幅应该是**首次进入练习页面**的时候显示，
//   而不是**每次同步都跳出来**」。所以判据是「**本机可能还没有云端最新进度**」——
//   与"此刻是否正在同步"解耦；同时由调用方加一道「本次进页面只提示一次」的闸门
//   （同一次停留期间后台又同步完/又失败，不重新弹；下次再进页面重新判）。
//
// 本模块只放纯判据，不含任何 IO，便于被测试直接切片跑。

/** 距上次成功拉取超过这么久，就当作「本机可能不是最新的」。
 *  取 1 分钟：比推送侧 8s 防抖 / 30s 最小间隔宽一点（那些动作刚跑完不该立刻抱怨）。
 *  注意：它**只决定横幅要不要出现**，不决定自动拉取的频率——后者是 App.vue 的 10 分钟节流，
 *  rabbit 2026-10-07 明确要保持那个节流（首屏留白 + 一页一次够了）。 */
export const STALE_PULL_MS = 60 * 1000

/**
 * 「近期自动拉取过」的认定窗口（2026-10-09，rabbit：要考虑自动拉的冷却，近期同步过就别弹）。
 *
 * 为什么单列这一条：启动自动拉取有**两道独立冷却**——① 距上次自动拉取 < 10 分钟就跳过本轮；
 * ② 自动同步开关关着也跳过。两者都会让「本机数据其实还是几秒前刚拉的」这种情况发生，
 * 而横幅判据只认 STALE_PULL_MS（1 分钟）⇒ 过了 1 分钟就笃定地说「可能读不到上次进度」，纯添乱。
 *
 * 取 10 分钟 = 与自动拉的节流同量级，但**两者语义不同、不得合并**：
 *   本常量只回答「还要不要抱怨本机不够新」，**不决定拉取频率**（拉取频率只有 cloud.ts 说了算）。
 *   旧口径「1 分钟陈旧窗口决定横幅、不决定拉取频率」不变；本常量在它之上再减掉一段"明知刚同步过"的噪音。
 */
export const RECENT_AUTO_PULL_MS = 10 * 60 * 1000

export interface EnterNoticeInput {
  /** 本机是否成功同步过（有成功记录） */
  synced: boolean
  /** 上次成功同步的时刻（毫秒）；未同步过传 0 */
  lastOkAt: number
  /** 上次同步是否以失败告终（失败后本机多半没拿到云端最新） */
  lastFail?: boolean
  /** 此刻是否有同步正在跑（最典型该提示的场景） */
  busy?: boolean
  /**
   * 此刻**是否真的在拉取**（云端 → 本机）。2026-10-07 新增：
   * `busy` 是全局锁口径，只推不拉的轻推也会点亮它 ⇒ 拿它判「本机可能还没拿到云端最新」
   * 会把「正在上传」误报成「正在下载」。有这条精确信号时以它为准。
   * 不传 = 退回旧的 `busy` 口径（兼容既有调用与测试）。
   */
  pullBusy?: boolean
  /**
   * 本次进页面**是否会**自动拉一次（`cloud.autoPullDueOnOpen()`）。2026-10-09 新增。
   *
   * 用于减噪：本轮**不会**自动拉（距上次自动拉 < 10 分钟，或自动同步开关关着）时，
   * 本机数据其实还是刚拉过的样子 ⇒ 不该按 1 分钟陈旧窗口抱怨「可能读不到上次进度」。
   * 不传 = 退回旧的纯陈旧窗口口径（兼容既有调用与测试）。
   */
  autoPullDue?: boolean
  /** 当前时刻（显式传入，便于测试） */
  now: number
}

/** 进页面那一刻是否该提示「可能读不到上次进度」。 */
export function shouldWarnOnEnter (i: EnterNoticeInput): boolean {
  // 2026-10-07：优先用「拉取在飞」这条精确信号 —— 只推不拉的轮次不该触发本提示。
  // 未传 pullBusy 时退回 busy（旧口径），保证既有调用方行为不变。
  const pulling = i.pullBusy !== undefined ? i.pullBusy : !!i.busy
  if (pulling) return true                      // 正在拉：此刻退出重进大概率能拿到，值得提示
  if (i.lastFail) return true                   // 上次失败：本机多半不是最新的

  // 2026-10-09（rabbit：直接进题库才是真实路径）：这里**不能**只看 `synced` 布尔值。
  //   `synced` 此前由内存 state === 'ok' 推出，刷新即归零 ⇒ 冷启动恒 false
  //   ⇒ 下面那行「从没成功同步过」把**所有**冷启动都吃掉，近期同步过也照弹（减噪永远走不到）。
  //   现在把「有没有成功记录」与「成功时刻」合并判断：有**任一**证据就算同步过
  //   （lastOkAt 现由持久化提供，冷启动也有值）。两者都空 = 真·从没成功同步过。
  const last = Number(i.lastOkAt) || 0
  if (!i.synced && !last) return true

  // 陈旧度：距今多久没成功拉到云端最新。
  const age = (Number(i.now) || 0) - last
  if (last && age <= STALE_PULL_MS) return false   // 刚同步过（边界取闭：正好等于不提示）

  // 2026-10-09：本轮**会**自动拉（或调用方没给这个信号 = 旧口径）⇒ 就该提示。
  // 此刻确实可能读到旧数据；拉完会由调用方自动收掉这条横幅。
  if (i.autoPullDue !== false) return true

  // 本轮**不会**自动拉（被 10 分钟节流跳过 / 自动同步开关关着）。
  // 近期确实同步过 ⇒ 本机数据够新，别唠叨。
  if (age <= RECENT_AUTO_PULL_MS) return false
  // 真陈旧（超过「近期」窗口）却又不拉 ⇒ 得让人知道本机不是最新的。
  return true
}
